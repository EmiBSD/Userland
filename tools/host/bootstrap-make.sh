# bootstrap-make.sh: build the base system's make(1) for the development host, from its
# inherited src/ and libutil's ohash, into target/host/bin/make. It is the one program built
# without make: every other one is built by this make with the share/mk of the same pin.
# The compiler is DevTools' clang (EMIBSD_LLVM_BIN), aimed at the host; src/ is only read.

set -eu
root=$(git rev-parse --show-toplevel)
llvm=${EMIBSD_LLVM_BIN:-$HOME/devel/emibsd/toolchains/llvm-23.1.4+emibsd.1-aarch64-apple-darwin/bin}
src=$root/base/usr/bin/development/make/src
util=$root/base/lib/system/libutil/src
obj=$root/target/host/make
out=$root/target/host/bin

[ -x "$llvm/clang" ] || { echo "bootstrap-make: no clang in $llvm (set EMIBSD_LLVM_BIN)" >&2; exit 1; }
case "$(uname -s)" in
Darwin) host="--target=$(uname -m)-apple-macos -isysroot $(xcrun --show-sdk-path)" ;;
*) echo "bootstrap-make: no host profile for $(uname -s)" >&2; exit 1 ;;
esac

# What the base system's <sys/param.h> tells make about the machine it runs on, which the
# host's does not: share/mk chooses the compiler and the flags from it.
case "$(uname -m)" in
arm64) host="$host -DMACHINE_ARCH=\"aarch64\" -DMACHINE_CPU=\"aarch64\"" ;;
x86_64) host="$host -DMACHINE_ARCH=\"amd64\" -DMACHINE_CPU=\"amd64\"" ;;
esac

# The values make's own Makefile gives its build, read from it so a pin bump carries them.
value() { sed -n "s/^$1=[[:space:]]*//p" "$src/Makefile"; }
cdefs=$(sed -n 's/^CDEFS+=//p' "$src/Makefile" | tr '\n' ' ')
var_slots=$(value MAGICVARSLOTS)
cond_slots=$(value MAGICCONDSLOTS)
srcs=$(sed -n '/^SRCS=/,/[^\\]$/p' "$src/Makefile" | sed 's/^SRCS=//; s/\\$//')
lst=$(sed -n '/^SRCS+=/,/[^\\]$/p' "$src/lst.lib/Makefile.inc" | sed 's/^SRCS+=//; s/\\$//')

rm -rf "$obj"
mkdir -p "$obj" "$out"
cc="$llvm/clang $host -include $root/tools/host/compat.h -std=gnu99 -O2 $cdefs -I$obj -I$src -I$src/lst.lib -I$util"

# The hash constants are generated by a helper of make's own, as its Makefile does.
$cc -o "$obj/generate" "$src/generate.c" "$src/stats.c" "$src/memory.c" "$util/ohash.c"
"$obj/generate" 1 "$var_slots" > "$obj/varhashconsts.h"
"$obj/generate" 2 "$cond_slots" > "$obj/condhashconsts.h"
"$obj/generate" 3 0 > "$obj/nodehashconsts.h"

files=
for f in $srcs; do files="$files $src/$f"; done
for f in $lst; do files="$files $src/lst.lib/$f"; done
$cc -o "$out/make" $files "$util/ohash.c"
echo "bootstrap-make: $out/make"
